#!/usr/bin/env node
// Regenerates scripts/generated/drill-pg.mjs: node-postgres (pg, as package-lock.json pins it, with every
// package it pulls in) bundled into one ES module by the pinned esbuild. The drill host runs the sync
// (scripts/drill-test-sync.mjs) from a checkout that never installed anything, so what it runs may import
// only node: modules and files the repository tracks (task 87d330d0, design FABLE-drill-sync-deps-20261124).
// pg-native stays outside: only the lazy pg.native getter requires it, and the sync never reads it.
// `--check` exits 1 when the committed module is out of date.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const app = new URL("../", import.meta.url);
const target = new URL("generated/drill-pg.mjs", import.meta.url);
const packageOf = input => /^node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input)?.[1] ?? null;

export async function renderDrillPgModule() {
  const result = await build({
    entryPoints: ["pg"],
    bundle: true,
    platform: "node",
    format: "esm",
    write: false,
    metafile: true,
    absWorkingDir: fileURLToPath(app).replace(/[\\/]$/, ""),
    // node_modules may be a link to a shared dependency store: the bundle names each file node_modules/<package>/... either way.
    preserveSymlinks: true,
    minify: false,
    legalComments: "inline",
    external: ["pg-native"],
    logLevel: "silent",
  });
  const names = [...new Set(Object.keys(result.metafile.inputs).map(packageOf).filter(name => name !== null))].sort();
  const manifest = async name => JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, app), "utf8"));
  const version = async name => (await manifest(name)).version;
  const versions = [];
  for (const name of names) { const { version: v, license } = await manifest(name); versions.push(`${name} ${v} (${license})`); }
  const lines = [
    "/* eslint-disable */",
    "// @ts-nocheck",
    `// Generated by scripts/generate-drill-pg.mjs from pg ${await version("pg")}; do not edit by hand.`,
    `// Bundled (esbuild ${await version("esbuild")}): ${versions.join(", ")}.`,
    // esbuild leaves a CommonJS require of a Node module as require(): an ES module has none, so it gets this file's own.
    "import { createRequire } from \"node:module\";",
    "const require = createRequire(import.meta.url);",
  ];
  return lines.join("\n") + "\n" + result.outputFiles[0].text.replace(/\r\n/g, "\n");
}

if (import.meta.main ?? process.argv[1]?.split(/[\\/]/).pop() === decodeURIComponent(import.meta.url.split('/').pop())) {
  const rendered = await renderDrillPgModule();
  if (process.argv.includes("--check")) {
    const current = (await readFile(target, "utf8").catch(() => "")).replace(/\r\n/g, "\n");
    if (current !== rendered) {
      console.error("scripts/generated/drill-pg.mjs is out of date; run node scripts/generate-drill-pg.mjs");
      process.exit(1);
    }
    console.log("drill pg module is current");
  } else {
    await writeFile(target, rendered);
    console.log("wrote scripts/generated/drill-pg.mjs");
  }
}
