#!/usr/bin/env node
// Regenerates worker/generated/pdf-cmaps.ts from the packed CJK CMaps shipped
// with the pinned pdfjs-dist (Adobe CMap resources, BSD-3-Clause, see
// node_modules/pdfjs-dist/cmaps/LICENSE). pdf.js needs them to decode text set
// in non-embedded CJK fonts with a predefined encoding (UniGB-UCS2-H, 90ms-RKSJ-H, ...)
// and to map Adobe-GB1/CNS1/Japan1/Korea1 CIDs to Unicode when a font has no
// ToUnicode. The UTF-8 / UTF-32 and JIS X 0213 variants are left out: PDFs
// rarely use them and they are the largest files; a request for a missing
// CMap is reported as text_unreliable, never as silent empty text.
// `--check` exits 1 when the committed module is out of date.
import { readdir, readFile, writeFile } from "node:fs/promises";

const source = new URL("../node_modules/pdfjs-dist/cmaps/", import.meta.url);
const target = new URL("../worker/generated/pdf-cmaps.ts", import.meta.url);
export const excludedCMap = name => /UTF8|UTF32|UniJIS2004|UniJISX0213/.test(name);

export async function renderPdfCMapModule() {
  const version = JSON.parse(await readFile(new URL("../package.json", source), "utf8")).version;
  const names = (await readdir(source)).filter(name => name.endsWith(".bcmap") && !excludedCMap(name)).sort();
  const license = (await readFile(new URL("LICENSE", source), "utf8")).trimEnd().split("\n").map(line => ("// " + line.replace(/^%%Copyright: ?/, "")).trimEnd());
  const lines = [
    "// Generated by scripts/generate-pdf-cmaps.mjs from pdfjs-dist " + version + " cmaps/",
    "// (Adobe CMap resources, BSD-3-Clause). Do not edit by hand. Their license:",
    ...license,
    `export const PDF_CMAPS_VERSION = ${JSON.stringify(version)};`,
    "/** Packed CMap file name (without .bcmap) -> base64 of the file. */",
    "export const PDF_CMAPS: Readonly<Record<string, string>> = Object.freeze({",
  ];
  for (const name of names)
    lines.push(`  ${JSON.stringify(name.slice(0, -".bcmap".length))}: ${JSON.stringify((await readFile(new URL(name, source))).toString("base64"))},`);
  lines.push("});", "");
  return lines.join("\n");
}

if (import.meta.main ?? process.argv[1]?.split(/[\\/]/).pop() === decodeURIComponent(import.meta.url.split('/').pop())) {
  const rendered = await renderPdfCMapModule();
  if (process.argv.includes("--check")) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== rendered) {
      console.error("worker/generated/pdf-cmaps.ts is out of date; run node scripts/generate-pdf-cmaps.mjs");
      process.exit(1);
    }
    console.log("pdf cmap module is current");
  } else {
    await writeFile(target, rendered);
    console.log("wrote worker/generated/pdf-cmaps.ts");
  }
}
