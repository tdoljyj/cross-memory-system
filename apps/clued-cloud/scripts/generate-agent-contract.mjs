#!/usr/bin/env node
// Regenerates worker/generated/agent-contract.ts from the single normative
// contract in protocol/agent/agent-contract.md, and
// worker/generated/components.ts from config/clued-components.json (the
// component versions the service reports). `--check` exits 1 when a committed
// module is out of date.
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const source = new URL("../../../protocol/agent/agent-contract.md", import.meta.url);
const target = new URL("../worker/generated/agent-contract.ts", import.meta.url);
const componentsSource = new URL("../../../config/clued-components.json", import.meta.url);
const componentsTarget = new URL("../worker/generated/components.ts", import.meta.url);

export async function renderAgentContractModule() {
  const text = (await readFile(source, "utf8")).replace(/\r\n/g, "\n");
  const match = /^Contract version: (\d+)$/m.exec(text);
  if (!match) throw new Error("agent-contract.md has no 'Contract version: N' line");
  return [
    "// Generated by scripts/generate-agent-contract.mjs from",
    "// protocol/agent/agent-contract.md. Do not edit by hand.",
    `export const AGENT_CONTRACT_MARKDOWN = ${JSON.stringify(text)};`,
    `export const AGENT_CONTRACT_VERSION = ${Number(match[1])};`,
    `export const AGENT_CONTRACT_SHA256 = ${JSON.stringify(createHash("sha256").update(text, "utf8").digest("hex"))};`,
    "",
  ].join("\n");
}

export async function renderComponentsModule() {
  const manifest = JSON.parse(await readFile(componentsSource, "utf8"));
  if (manifest.schema !== "clued.components/1" || !Array.isArray(manifest.components)) {
    throw new Error("config/clued-components.json is not a clued.components/1 manifest");
  }
  const versions = Object.fromEntries(manifest.components.map((c) => [c.id, String(c.version)]));
  if (!versions["mcp.server"]) throw new Error("config/clued-components.json has no mcp.server component");
  return [
    "// Generated by scripts/generate-agent-contract.mjs from",
    "// config/clued-components.json. Do not edit by hand.",
    `export const CLUED_COMPONENTS_SCHEMA = ${JSON.stringify(manifest.schema)};`,
    `export const CLUED_COMPONENT_VERSIONS: Readonly<Record<string, string>> = ${JSON.stringify(versions, null, 2)};`,
    `export const MCP_SERVER_VERSION = ${JSON.stringify(versions["mcp.server"])};`,
    "",
  ].join("\n");
}

if (import.meta.main ?? process.argv[1]?.split(/[\\/]/).pop() === decodeURIComponent(import.meta.url.split('/').pop())) {
  const outputs = [
    ["worker/generated/agent-contract.ts", target, await renderAgentContractModule()],
    ["worker/generated/components.ts", componentsTarget, await renderComponentsModule()],
  ];
  let stale = false;
  for (const [name, file, rendered] of outputs) {
    if (process.argv.includes("--check")) {
      const current = await readFile(file, "utf8").catch(() => "");
      if (current !== rendered) {
        console.error(`${name} is out of date; run node scripts/generate-agent-contract.mjs`);
        stale = true;
      } else {
        console.log(`${name} is current`);
      }
    } else {
      await writeFile(file, rendered);
      console.log(`wrote ${name}`);
    }
  }
  if (stale) process.exit(1);
}
