#!/usr/bin/env node
// Regenerates worker/generated/agent-contract.ts from the single normative
// contract in skills/clued/references/agent-contract.md. `--check` exits 1
// when the committed module is out of date.
import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const source = new URL("../../../skills/clued/references/agent-contract.md", import.meta.url);
const target = new URL("../worker/generated/agent-contract.ts", import.meta.url);

export async function renderAgentContractModule() {
  const text = await readFile(source, "utf8");
  const match = /^Contract version: (\d+)$/m.exec(text);
  if (!match) throw new Error("agent-contract.md has no 'Contract version: N' line");
  return [
    "// Generated by scripts/generate-agent-contract.mjs from",
    "// skills/clued/references/agent-contract.md. Do not edit by hand.",
    `export const AGENT_CONTRACT_MARKDOWN = ${JSON.stringify(text)};`,
    `export const AGENT_CONTRACT_VERSION = ${Number(match[1])};`,
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const rendered = await renderAgentContractModule();
  if (process.argv.includes("--check")) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== rendered) {
      console.error("worker/generated/agent-contract.ts is out of date; run node scripts/generate-agent-contract.mjs");
      process.exit(1);
    }
    console.log("agent contract module is current");
  } else {
    await writeFile(target, rendered);
    console.log("wrote worker/generated/agent-contract.ts");
  }
}
