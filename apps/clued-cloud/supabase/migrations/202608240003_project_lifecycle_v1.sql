-- Clued project lifecycle standard v1.
-- This migration is intentionally additive and is not applied automatically.

create table if not exists public.clued_projects (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120),
  normalized_name text not null check (char_length(normalized_name) between 1 and 120),
  aliases text[] not null default '{}'::text[],
  certainty_status text not null default 'unconfirmed'
    check (certainty_status in ('unconfirmed', 'confirmed')),
  progress_status text not null default 'not_started'
    check (progress_status in ('not_started', 'active', 'paused', 'completed', 'archived')),
  summary text check (summary is null or char_length(summary) <= 2000),
  confidence numeric(4,3) not null default 0.500
    check (confidence between 0 and 1),
  context_key text not null unique check (char_length(context_key) between 1 and 160),
  confirmed_at timestamptz,
  dismissed_at timestamptz,
  merged_into_project_id uuid references public.clued_projects(id) on delete set null,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  version bigint not null default 1 check (version > 0),
  constraint clued_projects_aliases_check check (cardinality(aliases) <= 20),
  constraint clued_projects_confirmation_check check (
    certainty_status = 'unconfirmed' or confirmed_at is not null
  ),
  constraint clued_projects_merge_check check (
    merged_into_project_id is null or merged_into_project_id <> id
  )
);

create unique index if not exists clued_projects_user_name_active_uidx
  on public.clued_projects(user_id, normalized_name)
  where merged_into_project_id is null;
create index if not exists clued_projects_user_status_idx
  on public.clued_projects(user_id, certainty_status, progress_status, updated_at desc)
  where dismissed_at is null and merged_into_project_id is null;
create index if not exists clued_projects_merged_into_idx
  on public.clued_projects(merged_into_project_id)
  where merged_into_project_id is not null;

create table if not exists public.clued_project_mentions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  project_id uuid not null references public.clued_projects(id) on delete cascade,
  binding_id uuid references public.clued_agent_bindings(id) on delete set null,
  operation text not null default 'observe' check (operation in ('observe', 'update', 'merge')),
  intent text not null check (intent in ('possible', 'confirmed', 'ignore')),
  evidence_summary text check (evidence_summary is null or char_length(evidence_summary) <= 500),
  confidence numeric(4,3) not null check (confidence between 0 and 1),
  source_ref text check (source_ref is null or char_length(source_ref) <= 160),
  idempotency_key text not null check (char_length(idempotency_key) between 8 and 160),
  created_at timestamptz not null default now(),
  unique (user_id, idempotency_key)
);

create index if not exists clued_project_mentions_project_idx
  on public.clued_project_mentions(project_id, created_at desc);
create index if not exists clued_project_mentions_binding_idx
  on public.clued_project_mentions(binding_id)
  where binding_id is not null;

alter table public.clued_projects enable row level security;
alter table public.clued_project_mentions enable row level security;

drop policy if exists clued_projects_owner_select on public.clued_projects;
create policy clued_projects_owner_select on public.clued_projects
  for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists clued_project_mentions_owner_select on public.clued_project_mentions;
create policy clued_project_mentions_owner_select on public.clued_project_mentions
  for select to authenticated using ((select auth.uid()) = user_id);

create or replace function clued_private.normalize_project_name(p_name text)
returns text
language sql
immutable
strict
set search_path = ''
as $$
  select lower(regexp_replace(btrim(p_name), '[[:space:][:punct:]]+', '', 'g'))
$$;

create or replace function clued_private.project_input_aliases(p_input jsonb)
returns text[]
language sql
immutable
set search_path = ''
as $$
  select coalesce(array_agg(alias order by alias), '{}'::text[])
  from (
    select distinct btrim(value) as alias
      from jsonb_array_elements_text(coalesce(p_input->'aliases', '[]'::jsonb)) as items(value)
     where char_length(btrim(value)) between 1 and 120
     limit 20
  ) aliases
$$;

create or replace function clued_private.project_observe_core(
  p_user_id uuid,
  p_binding_id uuid,
  p_input jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text := btrim(coalesce(p_input->>'name', ''));
  v_normalized_name text;
  v_intent text := coalesce(p_input->>'intent', 'possible');
  v_idempotency_key text := btrim(coalesce(p_input->>'idempotency_key', ''));
  v_confidence numeric := coalesce((p_input->>'confidence')::numeric,
    case when v_intent = 'confirmed' then 0.950 else 0.500 end);
  v_aliases text[] := clued_private.project_input_aliases(p_input);
  v_project public.clued_projects%rowtype;
  v_existing_project_id uuid;
  v_new_project_id uuid;
  v_receipt_id uuid;
  v_operation text;
  v_lock_key text;
begin
  if p_user_id is null then raise exception 'account_required' using errcode = '28000'; end if;
  if char_length(v_name) not between 1 and 120 then raise exception 'invalid_project_name' using errcode = '22023'; end if;
  if v_intent not in ('possible', 'confirmed', 'ignore') then raise exception 'invalid_project_intent' using errcode = '22023'; end if;
  if char_length(v_idempotency_key) not between 8 and 160 then raise exception 'invalid_idempotency_key' using errcode = '22023'; end if;
  if v_confidence not between 0 and 1 then raise exception 'invalid_confidence' using errcode = '22023'; end if;
  if char_length(coalesce(p_input->>'summary', '')) > 2000
     or char_length(coalesce(p_input->>'evidence_summary', '')) > 500
     or char_length(coalesce(p_input->>'source_ref', '')) > 160 then
    raise exception 'project_input_too_long' using errcode = '22023';
  end if;

    select m.project_id into v_existing_project_id
    from public.clued_project_mentions m
   where m.user_id = p_user_id and m.idempotency_key = v_idempotency_key;
  if found then
    select * into v_project from public.clued_projects where id = v_existing_project_id;
    return jsonb_build_object('status', 'idempotent', 'project', to_jsonb(v_project));
  end if;

  v_normalized_name := clued_private.normalize_project_name(v_name);
  if v_normalized_name = '' then raise exception 'invalid_project_name' using errcode = '22023'; end if;
  for v_lock_key in
    select distinct lock_key from (
      select v_normalized_name as lock_key
      union all
      select clued_private.normalize_project_name(alias) from unnest(v_aliases) as candidates(alias)
    ) locks where lock_key<>'' order by lock_key
  loop
    perform pg_advisory_xact_lock(hashtextextended(p_user_id::text || ':' || v_lock_key, 0));
  end loop;

  if exists (
    select 1 from public.clued_audit_receipts r
     where r.user_id=p_user_id and r.context_key='system:projects'
       and r.operation='ignore-project-mention'
       and r.metadata->>'idempotency_key'=v_idempotency_key
  ) then
    return jsonb_build_object('status','idempotent','project',null);
  end if;

  select p.* into v_project
    from public.clued_projects p
   where p.user_id = p_user_id
     and p.merged_into_project_id is null
     and (
       p.normalized_name = v_normalized_name
       or exists (
         select 1 from unnest(p.aliases) alias
          where clued_private.normalize_project_name(alias) = v_normalized_name
       )
     )
   order by (p.normalized_name = v_normalized_name) desc, p.created_at
   limit 1
   for update;

  if v_intent = 'ignore' and not found then
    insert into public.clued_audit_receipts(
      user_id,binding_id,context_key,operation,object_type,metadata
    ) values (
      p_user_id,p_binding_id,'system:projects','ignore-project-mention','project',
      jsonb_build_object('name',v_name,'idempotency_key',v_idempotency_key,'source_ref',p_input->>'source_ref')
    ) returning id into v_receipt_id;
    return jsonb_build_object('status','ignored','project',null,'receipt_id',v_receipt_id);
  end if;

  if not found then
    v_new_project_id := gen_random_uuid();
    insert into public.clued_projects(
      id,user_id,name,normalized_name,aliases,certainty_status,progress_status,summary,
      confidence,context_key,confirmed_at
    ) values (
      v_new_project_id,p_user_id,v_name,v_normalized_name,v_aliases,
      case when v_intent='confirmed' then 'confirmed' else 'unconfirmed' end,
      case when v_intent='confirmed' then coalesce(p_input->>'progress_status','not_started') else 'not_started' end,
      nullif(btrim(coalesce(p_input->>'summary','')),''),v_confidence,
      'project:' || v_new_project_id::text,
      case when v_intent='confirmed' then now() else null end
    ) returning * into v_project;
    v_operation := case when v_intent='confirmed' then 'create-confirmed-project' else 'create-unconfirmed-project' end;
  elsif v_intent = 'ignore' then
    update public.clued_projects
       set dismissed_at=now(), last_seen_at=now(), updated_at=now(), version=version+1
     where id=v_project.id returning * into v_project;
    v_operation := 'dismiss-project';
  else
    update public.clued_projects
       set certainty_status=case when v_intent='confirmed' then 'confirmed' else certainty_status end,
           confirmed_at=case when v_intent='confirmed' then coalesce(confirmed_at,now()) else confirmed_at end,
           dismissed_at=case when v_intent='confirmed' then null else dismissed_at end,
           progress_status=case when v_intent='confirmed' and p_input ? 'progress_status'
                                then p_input->>'progress_status' else progress_status end,
           summary=coalesce(nullif(btrim(coalesce(p_input->>'summary','')),''),summary),
           aliases=(select coalesce(array_agg(alias order by alias),'{}'::text[])
                      from (select distinct alias
                              from unnest(aliases || v_aliases || array[v_name]) as candidates(alias)
                             where clued_private.normalize_project_name(alias) <> normalized_name
                             limit 20) kept),
           confidence=greatest(confidence,v_confidence), last_seen_at=now(), updated_at=now(), version=version+1
     where id=v_project.id returning * into v_project;
    v_operation := case when v_intent='confirmed' and v_project.certainty_status='confirmed'
                        then 'confirm-project' else 'observe-project' end;
  end if;

  insert into public.clued_project_mentions(
    user_id,project_id,binding_id,operation,intent,evidence_summary,confidence,source_ref,idempotency_key
  ) values (
    p_user_id,v_project.id,p_binding_id,'observe',v_intent,
    nullif(btrim(coalesce(p_input->>'evidence_summary','')),''),v_confidence,
    nullif(btrim(coalesce(p_input->>'source_ref','')),''),v_idempotency_key
  );
  insert into public.clued_audit_receipts(
    user_id,binding_id,context_key,operation,object_type,object_id,version,metadata
  ) values (
    p_user_id,p_binding_id,'system:projects',v_operation,'project',v_project.id::text,v_project.version,
    jsonb_build_object('intent',v_intent,'confidence',v_confidence,'idempotency_key',v_idempotency_key)
  ) returning id into v_receipt_id;
  return jsonb_build_object(
    'status',v_operation,'project',to_jsonb(v_project),'receipt_id',v_receipt_id,
    'possible_duplicates',coalesce((
      select jsonb_agg(jsonb_build_object('id',p.id,'name',p.name))
        from public.clued_projects p
       where p.user_id=p_user_id and p.id<>v_project.id and p.dismissed_at is null
         and p.merged_into_project_id is null
         and (p.normalized_name like '%'||v_normalized_name||'%' or v_normalized_name like '%'||p.normalized_name||'%')
    ),'[]'::jsonb)
  );
exception
  when unique_violation then
    select p.* into v_project
      from public.clued_project_mentions m join public.clued_projects p on p.id=m.project_id
     where m.user_id=p_user_id and m.idempotency_key=v_idempotency_key;
    if not found then
      select * into v_project from public.clued_projects
       where user_id=p_user_id and normalized_name=v_normalized_name and merged_into_project_id is null;
    end if;
    return jsonb_build_object('status','concurrent-match','project',to_jsonb(v_project));
end;
$$;

create or replace function clued_private.project_list_core(p_user_id uuid, p_input jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_limit integer := least(greatest(coalesce((p_input->>'limit')::integer,100),1),200);
  v_projects jsonb;
begin
  if p_user_id is null then raise exception 'account_required' using errcode = '28000'; end if;
  select coalesce(jsonb_agg(to_jsonb(project_row) order by project_row.updated_at desc),'[]'::jsonb)
    into v_projects
    from (
      select p.*,
        (select count(*) from public.clued_project_mentions m where m.project_id=p.id) as mention_count
        from public.clued_projects p
       where p.user_id=p_user_id and p.merged_into_project_id is null
         and (coalesce((p_input->>'include_dismissed')::boolean,false) or p.dismissed_at is null)
         and (not (p_input ? 'certainty_status') or p.certainty_status=p_input->>'certainty_status')
         and (not (p_input ? 'progress_status') or p.progress_status=p_input->>'progress_status')
         and (not (p_input ? 'query') or p.name ilike '%'||replace(p_input->>'query','%','\%')||'%' escape '\')
       order by p.updated_at desc limit v_limit
    ) project_row;
  return jsonb_build_object('status','ok','projects',v_projects);
end;
$$;

create or replace function clued_private.project_update_core(
  p_user_id uuid,
  p_binding_id uuid,
  p_input jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_project_id uuid := (p_input->>'project_id')::uuid;
  v_target_id uuid;
  v_action text := coalesce(p_input->>'action','');
  v_idempotency_key text := btrim(coalesce(p_input->>'idempotency_key',''));
  v_project public.clued_projects%rowtype;
  v_target public.clued_projects%rowtype;
  v_receipt_id uuid;
  v_new_name text;
  v_new_normalized text;
  v_claim_id bigint;
  v_existing_project_id uuid;
begin
  if p_user_id is null then raise exception 'account_required' using errcode='28000'; end if;
  if v_action not in ('confirm','rename','dismiss','restore','set_progress','merge') then raise exception 'invalid_project_action' using errcode='22023'; end if;
  if char_length(v_idempotency_key) not between 8 and 160 then raise exception 'invalid_idempotency_key' using errcode='22023'; end if;
  select m.project_id into v_existing_project_id from public.clued_project_mentions m
   where m.user_id=p_user_id and m.idempotency_key=v_idempotency_key;
  if found then
    if v_existing_project_id<>v_project_id then raise exception 'idempotency_key_conflict' using errcode='23505'; end if;
    select * into v_project from public.clued_projects where id=v_project_id and user_id=p_user_id;
    return jsonb_build_object('status','idempotent','project',to_jsonb(v_project));
  end if;

  if v_action='merge' then
    v_target_id := (p_input->>'target_project_id')::uuid;
    if v_target_id=v_project_id then raise exception 'cannot_merge_project_into_itself' using errcode='22023'; end if;
    perform pg_advisory_xact_lock(hashtextextended(p_user_id::text || ':' || least(v_project_id,v_target_id)::text,0));
    perform pg_advisory_xact_lock(hashtextextended(p_user_id::text || ':' || greatest(v_project_id,v_target_id)::text,0));
    select * into v_project from public.clued_projects where id=v_project_id and user_id=p_user_id for update;
    select * into v_target from public.clued_projects where id=v_target_id and user_id=p_user_id and merged_into_project_id is null for update;
    if v_project.id is null or v_target.id is null then raise exception 'project_not_found' using errcode='P0002'; end if;
    insert into public.clued_project_mentions(user_id,project_id,binding_id,operation,intent,evidence_summary,confidence,source_ref,idempotency_key)
    values (p_user_id,v_project.id,p_binding_id,'merge','confirmed','Project merge',1,'project-lifecycle',v_idempotency_key)
    on conflict (user_id,idempotency_key) do nothing returning id into v_claim_id;
    if v_claim_id is null then return jsonb_build_object('status','idempotent','project',to_jsonb(v_project)); end if;
    update public.clued_projects set
      aliases=(select coalesce(array_agg(alias order by alias),'{}'::text[])
                 from (select distinct alias
                         from unnest(aliases||v_project.aliases||array[v_project.name]) as candidates(alias)
                        where clued_private.normalize_project_name(alias)<>normalized_name
                        limit 20) kept),
      confidence=greatest(confidence,v_project.confidence), updated_at=now(), version=version+1
      where id=v_target.id returning * into v_target;
    update public.clued_projects set merged_into_project_id=v_target.id,dismissed_at=now(),progress_status='archived',updated_at=now(),version=version+1
      where id=v_project.id returning * into v_project;
  else
    select * into v_project from public.clued_projects where id=v_project_id and user_id=p_user_id and merged_into_project_id is null for update;
    if v_project.id is null then raise exception 'project_not_found' using errcode='P0002'; end if;
    if p_input ? 'base_version' and (p_input->>'base_version')::bigint<>v_project.version then raise exception 'project_version_conflict' using errcode='40001'; end if;
    insert into public.clued_project_mentions(user_id,project_id,binding_id,operation,intent,evidence_summary,confidence,source_ref,idempotency_key)
    values (p_user_id,v_project.id,p_binding_id,'update',case when v_action='confirm' then 'confirmed' when v_action='dismiss' then 'ignore' else 'possible' end,
      'Lifecycle action: '||v_action,1,'project-lifecycle',v_idempotency_key)
    on conflict (user_id,idempotency_key) do nothing returning id into v_claim_id;
    if v_claim_id is null then return jsonb_build_object('status','idempotent','project',to_jsonb(v_project)); end if;
    if v_action='rename' then
      v_new_name:=btrim(coalesce(p_input->>'name',''));
      v_new_normalized:=clued_private.normalize_project_name(v_new_name);
      if char_length(v_new_name) not between 1 and 120 or v_new_normalized='' then raise exception 'invalid_project_name' using errcode='22023'; end if;
      perform pg_advisory_xact_lock(hashtextextended(p_user_id::text||':'||v_new_normalized,0));
    end if;
    update public.clued_projects set
      name=case when v_action='rename' then v_new_name else name end,
      normalized_name=case when v_action='rename' then v_new_normalized else normalized_name end,
      aliases=case when v_action='rename' then (
        select coalesce(array_agg(alias order by alias),'{}'::text[])
          from (select distinct alias from unnest(aliases||array[name]) as candidates(alias) limit 20) names
      ) else aliases end,
      certainty_status=case when v_action='confirm' then 'confirmed' else certainty_status end,
      confirmed_at=case when v_action='confirm' then coalesce(confirmed_at,now()) else confirmed_at end,
      dismissed_at=case when v_action='dismiss' then now() when v_action='restore' then null else dismissed_at end,
      progress_status=case when v_action='set_progress' then p_input->>'progress_status' else progress_status end,
      summary=case when p_input ? 'summary' then nullif(btrim(p_input->>'summary'),'') else summary end,
      updated_at=now(),version=version+1
      where id=v_project.id returning * into v_project;
  end if;
  insert into public.clued_audit_receipts(user_id,binding_id,context_key,operation,object_type,object_id,version,metadata)
  values (p_user_id,p_binding_id,'system:projects',v_action||'-project','project',v_project.id::text,v_project.version,
    jsonb_build_object('idempotency_key',v_idempotency_key,'target_project_id',v_target_id)) returning id into v_receipt_id;
  return jsonb_build_object('status',v_action||'d','project',to_jsonb(v_project),'target_project',to_jsonb(v_target),'receipt_id',v_receipt_id);
end;
$$;

create or replace function public.clued_project_observe(p_token_hash text,p_input jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_binding public.clued_agent_bindings%rowtype;
begin
  v_binding:=clued_private.resolve_binding(p_token_hash,'context:write','system:projects');
  return clued_private.project_observe_core(v_binding.user_id,v_binding.id,p_input);
end $$;
