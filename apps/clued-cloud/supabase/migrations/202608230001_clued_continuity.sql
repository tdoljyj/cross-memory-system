-- Clued cross-vendor continuity kernel.
-- Supabase Postgres remains the canonical store; Cloudflare is the edge/MCP adapter.

create extension if not exists pgcrypto;

create table if not exists public.clued_agent_bindings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  vendor text not null check (char_length(vendor) between 1 and 40),
  agent_name text not null check (char_length(agent_name) between 1 and 80),
  token_hash text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  scopes text[] not null default array['context:read', 'context:write', 'audit:read']::text[],
  created_at timestamptz not null default now(),
  last_used_at timestamptz,
  revoked_at timestamptz,
  constraint clued_agent_bindings_scopes_check check (
    scopes <@ array['context:read', 'context:write', 'audit:read']::text[]
    and cardinality(scopes) > 0
  )
);

create index if not exists clued_agent_bindings_user_idx
  on public.clued_agent_bindings(user_id, created_at desc);

create table if not exists public.clued_context_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  binding_id uuid references public.clued_agent_bindings(id) on delete set null,
  context_key text not null default 'global' check (char_length(context_key) between 1 and 160),
  event_type text not null check (
    event_type in ('decision', 'correction', 'action', 'failure', 'blocker', 'retraction', 'note')
  ),
  payload jsonb not null,
  base_version bigint check (base_version is null or base_version >= 0),
  occurred_at timestamptz not null default now()
);

create index if not exists clued_context_events_stream_idx
  on public.clued_context_events(user_id, context_key, id);

create table if not exists public.clued_context_checkpoints (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  binding_id uuid references public.clued_agent_bindings(id) on delete set null,
  context_key text not null check (char_length(context_key) between 1 and 160),
  version bigint not null check (version > 0),
  snapshot jsonb not null,
  summary text not null check (char_length(summary) between 1 and 4000),
  next_action text not null check (char_length(next_action) between 1 and 1000),
  last_event_id bigint not null default 0,
  previous_checkpoint_id uuid references public.clued_context_checkpoints(id),
  created_at timestamptz not null default now(),
  unique (user_id, context_key, version)
);

create index if not exists clued_context_checkpoints_stream_idx
  on public.clued_context_checkpoints(user_id, context_key, version desc);

create table if not exists public.clued_context_heads (
  user_id uuid not null references auth.users(id) on delete cascade,
  context_key text not null check (char_length(context_key) between 1 and 160),
  checkpoint_id uuid not null references public.clued_context_checkpoints(id) on delete cascade,
  version bigint not null check (version > 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, context_key)
);

create table if not exists public.clued_audit_receipts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  binding_id uuid references public.clued_agent_bindings(id) on delete set null,
  context_key text not null check (char_length(context_key) between 1 and 160),
  operation text not null,
  object_type text not null,
  object_id text,
  version bigint,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists clued_audit_receipts_stream_idx
  on public.clued_audit_receipts(user_id, context_key, created_at desc);

alter table public.clued_agent_bindings enable row level security;
alter table public.clued_context_events enable row level security;
alter table public.clued_context_checkpoints enable row level security;
alter table public.clued_context_heads enable row level security;
alter table public.clued_audit_receipts enable row level security;

