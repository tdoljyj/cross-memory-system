create or replace function public.clued_resolve_binding(
  p_token_hash text,
  p_required_scope text
)
returns table(binding_id uuid, user_id uuid, scopes text[])
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'invalid_binding' using errcode = '28000';
  end if;

  return query
  update public.clued_agent_bindings b
     set last_used_at = now()
   where b.token_hash = p_token_hash
     and b.revoked_at is null
     and p_required_scope = any(b.scopes)
  returning b.id, b.user_id, b.scopes;

  if not found then
    raise exception 'binding_not_authorized' using errcode = '42501';
  end if;
end;
$$;

create or replace function public.clued_mcp_restore(
  p_token_hash text,
  p_input jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_binding record;
  v_context_key text := coalesce(nullif(trim(p_input->>'context_key'), ''), 'global');
  v_checkpoint public.clued_context_checkpoints%rowtype;
  v_events jsonb;
  v_receipt_id uuid;
begin
  select * into strict v_binding
    from public.clued_resolve_binding(p_token_hash, 'context:read');

  if char_length(v_context_key) > 160 then
    raise exception 'context_key_too_long';
  end if;

  select c.* into v_checkpoint
    from public.clued_context_heads h
    join public.clued_context_checkpoints c on c.id = h.checkpoint_id
   where h.user_id = v_binding.user_id
     and h.context_key = v_context_key;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', e.id,
    'type', e.event_type,
    'payload', e.payload,
    'base_version', e.base_version,
    'occurred_at', e.occurred_at,
    'binding_id', e.binding_id
  ) order by e.id), '[]'::jsonb)
  into v_events
  from public.clued_context_events e
  where e.user_id = v_binding.user_id
    and e.context_key = v_context_key
    and e.id > coalesce(v_checkpoint.last_event_id, 0);

  insert into public.clued_audit_receipts(
    user_id, binding_id, context_key, operation, object_type, object_id, version,
    metadata
  ) values (
    v_binding.user_id, v_binding.binding_id, v_context_key, 'restore',
    'checkpoint', v_checkpoint.id::text, coalesce(v_checkpoint.version, 0),
    jsonb_build_object('pending_event_count', jsonb_array_length(v_events))
  ) returning id into v_receipt_id;

  return jsonb_build_object(
    'status', case when v_checkpoint.id is null then 'empty' else 'restored' end,
    'context_key', v_context_key,
    'version', coalesce(v_checkpoint.version, 0),
    'snapshot', coalesce(v_checkpoint.snapshot, '{}'::jsonb),
    'summary', v_checkpoint.summary,
    'next_action', v_checkpoint.next_action,
    'events_after_checkpoint', v_events,
    'provenance', jsonb_build_object(
      'canonical_store', 'clued-cloud/supabase',
      'checkpoint_id', v_checkpoint.id,
      'created_at', v_checkpoint.created_at,
      'source_binding_id', v_checkpoint.binding_id
    ),
    'receipt_id', v_receipt_id
  );
end;
$$;

create or replace function public.clued_mcp_append_event(
  p_token_hash text,
  p_input jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_binding record;
  v_context_key text := coalesce(nullif(trim(p_input->>'context_key'), ''), 'global');
  v_event_type text := p_input->>'event_type';
  v_payload jsonb := p_input->'payload';
  v_base_version bigint;
  v_event_id bigint;
  v_receipt_id uuid;
begin
  select * into strict v_binding
    from public.clued_resolve_binding(p_token_hash, 'context:write');

  if v_event_type not in ('decision', 'correction', 'action', 'failure', 'blocker', 'retraction', 'note') then
    raise exception 'invalid_event_type';
  end if;
  if v_payload is null or jsonb_typeof(v_payload) <> 'object' then
    raise exception 'payload_must_be_object';
  end if;
  if char_length(v_context_key) > 160 then
    raise exception 'context_key_too_long';
  end if;

  if p_input ? 'base_version' then
    v_base_version := (p_input->>'base_version')::bigint;
  end if;

  insert into public.clued_context_events(
    user_id, binding_id, context_key, event_type, payload, base_version
  ) values (
    v_binding.user_id, v_binding.binding_id, v_context_key, v_event_type,
    v_payload, v_base_version
  ) returning id into v_event_id;

  insert into public.clued_audit_receipts(
    user_id, binding_id, context_key, operation, object_type, object_id, version
  ) values (
    v_binding.user_id, v_binding.binding_id, v_context_key, 'append', 'event',
    v_event_id::text, v_base_version
  ) returning id into v_receipt_id;

  return jsonb_build_object(
    'status', 'appended',
    'event_id', v_event_id,
    'receipt_id', v_receipt_id,
    'context_key', v_context_key
  );
end;
$$;

create or replace function public.clued_mcp_commit_checkpoint(
  p_token_hash text,
  p_input jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_binding record;
  v_context_key text := coalesce(nullif(trim(p_input->>'context_key'), ''), 'global');
  v_base_version bigint := coalesce((p_input->>'base_version')::bigint, 0);
  v_snapshot jsonb := p_input->'snapshot';
  v_summary text := trim(coalesce(p_input->>'summary', ''));
  v_next_action text := trim(coalesce(p_input->>'next_action', ''));
  v_current_version bigint := 0;
  v_previous_id uuid;
  v_checkpoint_id uuid;
  v_last_event_id bigint := 0;
  v_receipt_id uuid;
begin
  select * into strict v_binding
    from public.clued_resolve_binding(p_token_hash, 'context:write');

  if v_snapshot is null or jsonb_typeof(v_snapshot) <> 'object' then
    raise exception 'snapshot_must_be_object';
  end if;
  if char_length(v_summary) not between 1 and 4000 then
    raise exception 'invalid_summary_length';
  end if;
  if char_length(v_next_action) not between 1 and 1000 then
    raise exception 'invalid_next_action_length';
  end if;
  if char_length(v_context_key) > 160 then
    raise exception 'context_key_too_long';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(v_binding.user_id::text || ':' || v_context_key, 0));

  select h.version, h.checkpoint_id
    into v_current_version, v_previous_id
    from public.clued_context_heads h
   where h.user_id = v_binding.user_id
     and h.context_key = v_context_key;
  v_current_version := coalesce(v_current_version, 0);

  if v_base_version <> v_current_version then
    return jsonb_build_object(
      'status', 'conflict',
      'error', 'stale_base_version',
      'expected_version', v_current_version,
      'provided_version', v_base_version,
      'context_key', v_context_key
    );
  end if;

  select coalesce(max(e.id), 0) into v_last_event_id
    from public.clued_context_events e
   where e.user_id = v_binding.user_id
     and e.context_key = v_context_key;

  insert into public.clued_context_checkpoints(
    user_id, binding_id, context_key, version, snapshot, summary, next_action,
    last_event_id, previous_checkpoint_id
  ) values (
    v_binding.user_id, v_binding.binding_id, v_context_key,
    v_current_version + 1, v_snapshot, v_summary, v_next_action,
    v_last_event_id, v_previous_id
  ) returning id into v_checkpoint_id;

  insert into public.clued_context_heads(user_id, context_key, checkpoint_id, version, updated_at)
  values (v_binding.user_id, v_context_key, v_checkpoint_id, v_current_version + 1, now())
  on conflict (user_id, context_key) do update
     set checkpoint_id = excluded.checkpoint_id,
         version = excluded.version,
         updated_at = excluded.updated_at;

  insert into public.clued_audit_receipts(
    user_id, binding_id, context_key, operation, object_type, object_id, version,
    metadata
  ) values (
    v_binding.user_id, v_binding.binding_id, v_context_key, 'checkpoint',
    'checkpoint', v_checkpoint_id::text, v_current_version + 1,
    jsonb_build_object('base_version', v_base_version, 'last_event_id', v_last_event_id)
  ) returning id into v_receipt_id;

  return jsonb_build_object(
    'status', 'committed',
    'context_key', v_context_key,
    'version', v_current_version + 1,
    'checkpoint_id', v_checkpoint_id,
    'receipt_id', v_receipt_id,
    'last_event_id', v_last_event_id
  );
end;
$$;

create or replace function public.clued_mcp_search_context(
  p_token_hash text,
  p_input jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_binding record;
  v_context_key text := coalesce(nullif(trim(p_input->>'context_key'), ''), 'global');
  v_query text := trim(coalesce(p_input->>'query', ''));
  v_include_history boolean := coalesce((p_input->>'include_history')::boolean, false);
  v_limit integer := least(greatest(coalesce((p_input->>'limit')::integer, 10), 1), 50);
  v_pattern text;
  v_checkpoints jsonb;
  v_events jsonb;
begin
  select * into strict v_binding
    from public.clued_resolve_binding(p_token_hash, 'context:read');
  if char_length(v_query) not between 1 and 500 then
    raise exception 'invalid_query_length';
  end if;
  v_pattern := '%' || v_query || '%';

  select coalesce(jsonb_agg(row_data order by version desc), '[]'::jsonb)
  into v_checkpoints
  from (
    select jsonb_build_object(
      'kind', 'checkpoint', 'id', c.id, 'version', c.version,
      'summary', c.summary, 'next_action', c.next_action,
      'snapshot', c.snapshot, 'created_at', c.created_at
    ) as row_data, c.version
    from public.clued_context_checkpoints c
    where c.user_id = v_binding.user_id
      and c.context_key = v_context_key
      and (c.summary ilike v_pattern or c.next_action ilike v_pattern or c.snapshot::text ilike v_pattern)
      and (v_include_history or c.id = (
        select h.checkpoint_id from public.clued_context_heads h
        where h.user_id = v_binding.user_id and h.context_key = v_context_key
      ))
    order by c.version desc
    limit v_limit
  ) matches;

  select coalesce(jsonb_agg(row_data order by id desc), '[]'::jsonb)
  into v_events
  from (
    select jsonb_build_object(
      'kind', 'event', 'id', e.id, 'type', e.event_type,
      'payload', e.payload, 'base_version', e.base_version,
      'occurred_at', e.occurred_at
    ) as row_data, e.id
    from public.clued_context_events e
    where e.user_id = v_binding.user_id
      and e.context_key = v_context_key
      and e.payload::text ilike v_pattern
    order by e.id desc
    limit v_limit
  ) matches;

  return jsonb_build_object(
    'status', 'ok',
    'mode', 'lexical',
    'context_key', v_context_key,
    'query', v_query,
    'checkpoints', v_checkpoints,
    'events', v_events
  );
end;
$$;

create or replace function public.clued_mcp_audit_receipts(
  p_token_hash text,
  p_input jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_binding record;
  v_context_key text := coalesce(nullif(trim(p_input->>'context_key'), ''), 'global');
  v_limit integer := least(greatest(coalesce((p_input->>'limit')::integer, 20), 1), 100);
  v_receipts jsonb;
begin
  select * into strict v_binding
    from public.clued_resolve_binding(p_token_hash, 'audit:read');

  select coalesce(jsonb_agg(row_data order by created_at desc), '[]'::jsonb)
  into v_receipts
  from (
    select jsonb_build_object(
      'id', r.id,
      'operation', r.operation,
      'object_type', r.object_type,
      'object_id', r.object_id,
      'version', r.version,
      'binding_id', r.binding_id,
      'metadata', r.metadata,
      'created_at', r.created_at
    ) as row_data, r.created_at
    from public.clued_audit_receipts r
    where r.user_id = v_binding.user_id
      and r.context_key = v_context_key
    order by r.created_at desc
    limit v_limit
  ) matches;

  return jsonb_build_object(
    'status', 'ok',
    'context_key', v_context_key,
    'receipts', v_receipts
  );
end;
$$;

