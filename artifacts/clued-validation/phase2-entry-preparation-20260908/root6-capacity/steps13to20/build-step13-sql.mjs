// Emits step13-exec.sql from the reviewed registration candidate. Run it rather than
// transcribing the body by hand: the request object must reach append_event unchanged, and
// hand-copying a 4 KB JSON literal into SQL is the one transcription this programme cannot
// audit after the fact (append_event does not validate the body -- it stores whatever arrives
// and the generation id is then burned).
//
//   node build-step13-sql.mjs            # writes step13-exec.sql next to this file
//
// It performs no database access and no write other than that one file.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert';
import {fileURLToPath} from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..', '..', '..', '..');
const CAND = 'artifacts/clued-validation/phase2-entry-preparation-20260908/bootstrap/next-window-20260912/root6-registration/Root6GenerationRegistration.candidate.json';

const raw = fs.readFileSync(path.join(REPO, CAND), 'utf8');
const doc = JSON.parse(raw);
const req = doc.request;

// The exact key set append_event(jsonb):7 demands. Anything else raises invalid_scope_or_fields.
assert.deepEqual(Object.keys(req).sort(),
  ['body','expected_sequence','generation_id','idempotency_key','kind','metadata_binding_sha256',
   'predecessor_generation_id','root_set_id'],
  'REQUEST_KEY_SET_MUST_MATCH_append_event_LINE_7');
assert.equal(typeof req.body, 'object');
assert.match(req.idempotency_key, /^[A-Za-z0-9_-]{1,128}$/);
assert.ok(Number.isInteger(req.expected_sequence));
assert.equal(req.kind, 'GENERATION_REGISTERED');
assert.equal(req.generation_id, 'ctrgen_5e0440a95ac8ee257b9e4236cabd275b');
assert.equal(req.predecessor_generation_id, 'ctrgen_e5df432221344996afc04b5638121d96');
assert.equal(req.root_set_id, 'ctr_414bd3c724264a83894b0c55cf2ab878');

const text = JSON.stringify(req);
// append_event(jsonb):5 -- octet_length(p::text)>65536 raises invalid_request. Postgres
// re-serialises jsonb, so this is an approximation with a wide margin, not the exact figure.
assert.ok(Buffer.byteLength(text) < 60000, 'REQUEST_TOO_LARGE_FOR_append_event');
assert.ok(!text.includes('$step13$'), 'DOLLAR_TAG_COLLISION');

const sql = `-- GENERATED by build-step13-sql.mjs from
--   ${CAND}
-- candidate file sha256: ${crypto.createHash('sha256').update(raw).digest('hex')}
-- request object bytes (JS serialisation): ${Buffer.byteLength(text)}
-- DO NOT EDIT. Regenerate instead.
--
-- STEP 13. IRREVERSIBLE. Burns ctrgen_5e0440a95ac8ee257b9e4236cabd275b permanently.
-- Run step13-pre.sql first and confirm every column. Run step13-readback.sql immediately after.
-- If this statement is interrupted with no result, DO NOT re-run it. Go to step13-readback.sql.

select clued_control.append_event($step13$${text}$step13$::jsonb) as append_event_result;
`;
fs.writeFileSync(path.join(HERE, 'step13-exec.sql'), sql);

// The read-back embeds the same literal so that "is this the reviewed body?" is answered by
// jsonb equality against the reviewed bytes, not by eyeballing a digest. Generated from the
// same source in the same run, so the two files cannot drift apart.
const readback = `-- GENERATED by build-step13-sql.mjs. DO NOT EDIT. Regenerate instead.
-- candidate file sha256: ${crypto.createHash('sha256').update(raw).digest('hex')}
--
-- STEP 13 READ-BACK. Read-only. Run IMMEDIATELY after step13-exec.sql -- including, and
-- especially, when step13-exec.sql returned nothing, errored, or was cut off. This is the only
-- way to learn whether the write landed. Never re-run step13-exec.sql before running this.
--
-- Interpreting the result:
--
--   landed = true and body_is_the_reviewed_one = true
--       Step 13 succeeded. Proceed to step 13a (work/cp01/measure-root6-root-digest.sql).
--
--   landed = false
--       Nothing was appended; the generation is NOT burned. Re-run step13-pre.sql. If it is
--       still all-true, step 13 may be attempted again with this same generated file.
--
--   landed = true and body_is_the_reviewed_one = false
--       ABORT THE PROGRAMME. A GENERATION_REGISTERED event exists for this generation but does
--       not carry the reviewed body. The generation id is burned and the controller will reject
--       it. Do not attempt a correction: append_event:36 forbids registering this generation
--       again and the events table is append-only. Record the state and stop.

with reg as (
  select * from clued_control.events
   where root_id='ctr_414bd3c724264a83894b0c55cf2ab878'
     and request->>'kind'='GENERATION_REGISTERED'
     and request->>'generation_id'='ctrgen_5e0440a95ac8ee257b9e4236cabd275b'
)
select
  clock_timestamp()                                               as observed_at,
  exists (select 1 from reg)                                      as landed,
  (select request = $step13rb$${text}$step13rb$::jsonb from reg)   as body_is_the_reviewed_one,
  (select sequence from reg)                                      as event_sequence,
  (select idempotency_key from reg)                               as idempotency_key,
  (select recorded_at from reg)                                   as recorded_at,
  (select encode(sha256(convert_to(request::text,'UTF8')),'hex') from reg)
                                                                  as stored_request_digest,
  (select generation_id from clued_control.current_head
    where root_id='ctr_414bd3c724264a83894b0c55cf2ab878')          as head_generation_now,
  (select sequence from clued_control.current_head
    where root_id='ctr_414bd3c724264a83894b0c55cf2ab878')          as head_sequence_now,
  (select count(*) from clued_control.events)                      as events_rows_now,
  (select charged_seconds from clued_control.execution_current)    as charged_seconds,
  (select sequence from clued_control.execution_current)           as execution_sequence,
  (select active_ga_id from clued_control.execution_current)       as active_ga_id,
  (select pending_budget_sequence from clued_control.execution_current) as pending_budget_sequence,
  (select count(*) from clued_control.execution_events)            as exec_event_rows;

-- Expected after a successful step 13:
--   landed t | body_is_the_reviewed_one t | event_sequence 6
--   head_generation_now ctrgen_5e0440a95ac8ee257b9e4236cabd275b | head_sequence_now 6
--   events_rows_now 6 | charged_seconds 9906 | execution_sequence 88
--   active_ga_id NULL | pending_budget_sequence NULL | exec_event_rows 88
`;
fs.writeFileSync(path.join(HERE, 'step13-readback.sql'), readback);

console.log(JSON.stringify({
  state: 'STEP13_SQL_GENERATED_NOT_EXECUTED',
  out: ['step13-exec.sql', 'step13-readback.sql'],
  candidate_sha256: crypto.createHash('sha256').update(raw).digest('hex'),
  idempotency_key: req.idempotency_key,
  expected_sequence: req.expected_sequence,
  metadata_binding_sha256: req.metadata_binding_sha256,
  authority_effect: 'NONE',
}, null, 2));
