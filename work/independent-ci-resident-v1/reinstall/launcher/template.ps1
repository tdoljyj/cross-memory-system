function Get-Key($d, [string]$k) {
  if ($null -eq $d -or $d -isnot [Collections.IDictionary]) { return $null }
  $has = if ($d.PSObject.Methods['ContainsKey']) { $d.ContainsKey($k) } else { $d.Contains($k) }   # generic Dictionary / OrderedDictionary
  if ($has) { $d[$k] } else { $null }
}
# Whole text, else the last top-level object (a line that is exactly '{' up to the end), as ConvertTo-Json prints it.
function Parse-Json([string]$text) {
  if ($null -eq $text) { return $null }
  $t = $text.Trim([char]0xFEFF, ' ', "`r", "`n", "`t"); if (-not $t) { return $null }
  try { return $Js.DeserializeObject($t) } catch { }
  $at = $t.LastIndexOf("`n{"); if ($at -lt 0) { return $null }
  try { return $Js.DeserializeObject($t.Substring($at + 1)) } catch { return $null }
}
function Parse-LastLine([string]$text) { if ($null -eq $text) { return $null }; $l = @($text -split "`r?`n" | Where-Object { $_.Trim() }); if ($l.Count -eq 0) { return $null }; Parse-Json $l[$l.Count - 1] }
