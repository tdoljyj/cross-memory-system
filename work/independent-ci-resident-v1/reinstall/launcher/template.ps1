function Step-PauseAfterInstall([bool]$verified) {
  $r = [ordered]@{ verified = $verified; request = $null; requestSha256 = $null; staged = $null; daclReadback = $null; confirmed = $false; paused = $null; found = $null; residentStop = $null; residentStopped = $null; waitSeconds = $PauseWaitSeconds; error = $null }
  try {
    $body = $U8.GetBytes('{"contract":"clued.independent-ci.resident-pause/1","reason":"' + $PauseReason + '"}')
    $rnd = New-Object byte[] 6; $rng = [Security.Cryptography.RandomNumberGenerator]::Create(); try { $rng.GetBytes($rnd) } finally { $rng.Dispose() }
    $name = ([DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()).ToString('0000000000000') + '-' + ([BitConverter]::ToString($rnd)).Replace('-', '').ToLowerInvariant() + '.json'
    $r.request = $name; $r.requestSha256 = Sha256Bytes $body
    $tmp = Join-Path $Stage ('pause-request-' + $name)
    $r.staged = $tmp
    $fsec = New-Object Security.AccessControl.FileSecurity
    $fsec.SetSecurityDescriptorSddlForm($PauseRequestDacl, [Security.AccessControl.AccessControlSections]::Access)
    $h = New-Object IO.FileStream -ArgumentList $tmp, ([IO.FileMode]::CreateNew), ([Security.AccessControl.FileSystemRights]::Write), ([IO.FileShare]::None), 4096, ([IO.FileOptions]::WriteThrough), $fsec
    try { $h.Write($body, 0, $body.Length); $h.Flush($true) } finally { $h.Dispose() }
    $r.daclReadback = [IO.File]::GetAccessControl($tmp).GetSecurityDescriptorSddlForm([Security.AccessControl.AccessControlSections]::Access)
    if ($r.daclReadback -cne $fsec.GetSecurityDescriptorSddlForm([Security.AccessControl.AccessControlSections]::Access)) { throw 'PAUSE_REQUEST_DACL_READBACK_MISMATCH' }
    if ((Get-FileSha $tmp) -cne $r.requestSha256) { throw 'PAUSE_REQUEST_STAGED_COPY_CHANGED' }
    [IO.File]::Move($tmp, (Join-Path (Join-Path $ResidentRoot 'requests') $name))
    $pausedFile = Join-Path $ResidentRoot 'state\PAUSED.json'
    $want = $r.requestSha256
    $r.confirmed = Wait-Until { [IO.File]::Exists($pausedFile) -and ((Get-Key (Get-Key (Parse-Json ([IO.File]::ReadAllText($pausedFile))) 'source') 'requestSha256') -ceq $want) } $PauseWaitSeconds
    if ([IO.File]::Exists($pausedFile)) { $r.paused = [ordered]@{ sha256 = (Get-FileSha $pausedFile); text = (Tail ([IO.File]::ReadAllText($pausedFile))) } }
  } catch { $r.error = $_.Exception.Message }
