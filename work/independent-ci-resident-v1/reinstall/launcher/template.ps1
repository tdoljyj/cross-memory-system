# The archive tool's allow-list (protocol records only): incoming result/challenge-NN, outgoing issue/response-NN
# (.json and .ready.json) and outgoing\active.lock. Journals, observations.jsonl and .bak files are not records.
function Get-SpoolLeftovers([string]$spool) {
  $seq = @(1..32 | ForEach-Object { $_.ToString('00') })
  $names = @{ incoming = @('result') + @($seq | ForEach-Object { 'challenge-' + $_ }); outgoing = @('issue') + @($seq | ForEach-Object { 'response-' + $_ }) }
  $found = [ordered]@{}
  foreach ($folder in @('incoming', 'outgoing')) { foreach ($n in $names[$folder]) { foreach ($suffix in @('.json', '.ready.json')) {
    $p = Join-Path (Join-Path $spool $folder) ($n + $suffix); if ([IO.File]::Exists($p)) { $found[$folder + '/' + $n + $suffix] = Sha256Bytes ([IO.File]::ReadAllBytes($p)) } } } }
  $lock = Join-Path $spool 'outgoing\active.lock'; if ([IO.File]::Exists($lock)) { $found['outgoing/active.lock'] = Sha256Bytes ([IO.File]::ReadAllBytes($lock)) }
  $found
}
# Everything the archive tool would report as remainder (its own rules): any other entry in incoming, an
# outgoing entry that is neither a record nor a kept journal/observations/.bak name, and a spool-root entry other
# than incoming, outgoing and archive|failed|completed-* directories. A remainder makes every later
# completed-protocol archive of the resident (success-close, between-roles-N) refuse, so it is checked here.
function Get-SpoolRemainder([string]$spool, $found) {
  $keep = '^(?:[0-9a-f]{64}\.json(?:\.lock|\.[0-9a-f-]{36}\.tmp)?|observations\.jsonl|active\.lock\.clued-[a-z0-9-]+\.bak)$'
  $rem = @()
  foreach ($folder in @('incoming', 'outgoing')) { foreach ($e in [IO.Directory]::GetFileSystemEntries((Join-Path $spool $folder))) {
    $leaf = [IO.Path]::GetFileName($e); if ($found.Contains($folder + '/' + $leaf)) { continue }
    if ($folder -ceq 'incoming' -or $leaf -cnotmatch $keep) { $rem += ($folder + '/' + $leaf) } } }
  foreach ($e in [IO.Directory]::GetFileSystemEntries($spool)) { $leaf = [IO.Path]::GetFileName($e); if ($leaf -cnotin @('incoming', 'outgoing') -and $leaf -cnotmatch '^(?:archive|failed|completed)-[A-Za-z0-9-]+$') { $rem += $leaf } }
  , $rem
}
function Test-LeftoversAsPinned($found) {
