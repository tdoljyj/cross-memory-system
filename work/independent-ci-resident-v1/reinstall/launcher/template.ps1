# The staging parent is created once with owner BA and a protected SY/BA DACL; an existing parent must carry
# exactly that (a squatted or re-ACLed one refuses). Each run stages into its own new child directory, so a
# stopped run never blocks a later one. Every staged file must be owned by BA (no implicit WRITE_DAC for the Owner).
function Step-Stage($buffers, [string]$sddl, [string]$owner = 'S-1-5-32-544') {
  $ds = New-Object Security.AccessControl.DirectorySecurity; $ds.SetSecurityDescriptorSddlForm($sddl)
  if ([IO.File]::Exists($StageParent)) { Stop-Launch 'STAGING_PARENT_IS_A_FILE' $StageParent }
  if (-not [IO.Directory]::Exists($StageParent)) { [void][IO.Directory]::CreateDirectory($StageParent, $ds) }
  if (([IO.File]::GetAttributes($StageParent) -band [IO.FileAttributes]::ReparsePoint) -ne 0) { Stop-Launch 'STAGING_PARENT_REPARSE_REFUSED' $StageParent }
  $back = [IO.Directory]::GetAccessControl($StageParent).GetSecurityDescriptorSddlForm('All')
  if ($back -cne $ds.GetSecurityDescriptorSddlForm('All')) { Stop-Launch 'STAGING_ACL_READBACK_MISMATCH' $back }
  $dir = Join-Path $StageParent ([DateTimeOffset]::UtcNow.ToString('yyyyMMddTHHmmssZ') + '-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))
  if ([IO.Directory]::Exists($dir) -or [IO.File]::Exists($dir)) { Stop-Launch 'STAGING_DIRECTORY_EXISTS' $dir }
  [void][IO.Directory]::CreateDirectory($dir)
  foreach ($sub in @('tmp', 'tmp\appdata', 'tmp\localappdata')) { [void][IO.Directory]::CreateDirectory((Join-Path $dir $sub)) }
  $tmp = Join-Path $dir 'tmp'; $ChildEnv['TEMP'] = $tmp; $ChildEnv['TMP'] = $tmp; $ChildEnv['APPDATA'] = Join-Path $tmp 'appdata'; $ChildEnv['LOCALAPPDATA'] = Join-Path $tmp 'localappdata'
  foreach ($name in @($buffers.Keys)) {
    $p = Join-Path $dir $name; Write-New $p $buffers[$name]
    if ((Sha256Bytes ([IO.File]::ReadAllBytes($p))) -cne $Staged[$name][1]) { Stop-Launch 'STAGED_COPY_CHANGED' $name }
    $o = [IO.File]::GetAccessControl($p).GetOwner([Security.Principal.SecurityIdentifier]).Value
    if ($o -cne $owner) { Stop-Launch 'STAGED_COPY_OWNER_NOT_ADMINISTRATORS' ($name + ':' + $o) }
  }
  $Done.Add('stage')
  $dir
}
