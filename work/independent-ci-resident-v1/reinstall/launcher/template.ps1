    $entry = @(Get-Key $pkg 'files' | Where-Object { (Get-Key $_ 'path') -ceq $rel })
    if ($entry.Count -ne 1 -or (Get-Key $entry[0] 'sha256') -cne $want) { Stop-Launch 'PACKAGE_PIN_MISMATCH' $name }
