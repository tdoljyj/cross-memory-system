    $r.residentStop = (& $Sc stop CluedCIResident | Out-String).Trim()
    $r.residentStopped = Wait-Until { ((Get-ScState 'CluedCIResident').state -eq 1) -and -not (Test-ExecutorAlive).alive } 600
