# Whole text, else the last top-level object (a line that is exactly '{' up to the end), as ConvertTo-Json prints it.
function Parse-Json([string]$text) {
  if ($null -eq $text) { return $null }
  $t = $text.Trim([char]0xFEFF, ' ', "`r", "`n", "`t"); if (-not $t) { return $null }
  try { return $Js.DeserializeObject($t) } catch { }
  $at = $t.LastIndexOf("`n{"); if ($at -lt 0) { return $null }
  try { return $Js.DeserializeObject($t.Substring($at + 1)) } catch { return $null }
}
