    if ($k -ceq 'stdout') { $r.stdout = $text } else { $r.stderrTail = (Tail $text) }
    if ($null -ne $text) { Write-New (Join-Path $Out ('linux-' + $name + '.' + $k + '.txt')) ($U8.GetBytes($text)) }
  }
  $r
}
