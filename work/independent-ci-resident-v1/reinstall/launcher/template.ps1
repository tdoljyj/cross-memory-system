  $report = [ordered]@{}
  # r7 r2: first the upgrader, through SCM (it runs under the root as LocalSystem and SCM restarts it after a failure, so it is never
  # killed): its host ends it at a step boundary, at most 60 s, as the installed uninstall does first; the uninstall deletes it stopped
  $report['upgraderStop'] = (& $Sc stop CluedCIUpgrader | Out-String).Trim()
  $report['upgraderStopped'] = Wait-Until { $u = Get-ScState 'CluedCIUpgrader'; $u.gone -or $u.state -eq 1 } 180
  if (-not $report['upgraderStopped']) { $report['after'] = [ordered]@{ upgrader = (Get-ScState 'CluedCIUpgrader') }; Write-Json 'quiesce-report.json' $report; Stop-Launch 'QUIESCE_NOT_CONFIRMED' $report }
  $report['residentStop'] = (& $Sc stop CluedCIResident | Out-String).Trim()
  $report['residentStopped'] = Wait-Until { ((Get-ScState 'CluedCIResident').state -eq 1) -and -not (Test-ExecutorAlive).alive } 600
  if (-not $report['residentStopped']) { $report['after'] = [ordered]@{ services = @((Get-ScState 'CluedCIResident'), (Get-ScState 'CluedCISwapBroker')); executor = Test-ExecutorAlive }; Write-Json 'quiesce-report.json' $report; Stop-Launch 'QUIESCE_NOT_CONFIRMED' $report }
  $report['brokerStop'] = (& $Sc stop CluedCISwapBroker | Out-String).Trim()
  $report['brokerStopped'] = Wait-Until { (Get-ScState 'CluedCISwapBroker').state -eq 1 } 120
  if (-not $report['brokerStopped']) { $report['after'] = [ordered]@{ services = @((Get-ScState 'CluedCIResident'), (Get-ScState 'CluedCISwapBroker')) }; Write-Json 'quiesce-report.json' $report; Stop-Launch 'QUIESCE_NOT_CONFIRMED' $report }
  $report['companionTaskStop'] = try { Stop-CompanionTask; 'stopped' } catch { $_.Exception.Message }
  $report['processesBeforeKill'] = @(Get-ProcessesUnderRoot)
  foreach ($p in $report['processesBeforeKill']) { Stop-Process -Id $p.pid -Force -ErrorAction SilentlyContinue }
  $report['noProcessUnderRoot'] = Wait-Until { @(Get-ProcessesUnderRoot).Count -eq 0 } 60
  $report['after'] = [ordered]@{ services = @((Get-ScState 'CluedCIResident'), (Get-ScState 'CluedCISwapBroker')); executor = Test-ExecutorAlive; processesUnderRoot = @(Get-ProcessesUnderRoot) }
  Write-Json 'quiesce-report.json' $report
  if (-not ($report['residentStopped'] -and $report['brokerStopped'] -and $report['noProcessUnderRoot'])) { Stop-Launch 'QUIESCE_NOT_CONFIRMED' $report }
  $Done.Add('quiesce')
  $report
}
# The installed uninstall-resident.ps1: dry run, plan fields, -Apply with exactly that plan; then the kept
# evidence is checked byte for byte and both service deletions and the rename are confirmed.
function Step-Uninstall {
  $report = [ordered]@{}
  $d = Invoke-Child 'uninstall.dry-run' $InstalledUninstall @()
  $dv = Parse-Json $d.stdout; $dp = Get-Key $dv 'plan'; $sha = [string](Get-Key $dv 'planSha256')
  $report['dryRun'] = [ordered]@{ exit = $d.exit; status = (Get-Key $dv 'status'); planSha256 = $sha; plan = $dp; stderr = (Tail $d.stderr) }
  if ($d.exit -ne 0 -or (Get-Key $dv 'status') -cne 'DRY_RUN_PLAN_ONLY_NOTHING_WRITTEN' -or $sha -cnotmatch '^[0-9a-f]{64}$' -or -not (Test-UninstallPlan $dp) -or (Get-Key $dp 'executorAlive') -ne $false) { Stop-Launch 'UNINSTALL_PLAN_REFUSED' $report }
  $quiet = Test-OldRootQuiet; $report['oldRootQuietBeforeApply'] = $quiet   # r4 Q1
  if (@($quiet.codes).Count) { Write-Json 'uninstall-report.json' $report; Stop-Launch ([string]@($quiet.codes)[0]) $report }
  if (-not (Test-TerminalEvidence $ResidentRoot)) { Stop-Launch 'TERMINAL_EVIDENCE_CHANGED_BEFORE_UNINSTALL' $report }
  $a = Invoke-Child 'uninstall' $InstalledUninstall @('-Apply', '-ExpectedPlanSha256', $sha)
  $av = Parse-Json $a.stdout; $kept = [string](Get-Key $av 'keptAt')
  $report['apply'] = [ordered]@{ exit = $a.exit; status = (Get-Key $av 'status'); keptAt = $kept; stdout = (Tail $a.stdout); stderr = (Tail $a.stderr) }
  if ($a.exit -ne 0 -or (Get-Key $av 'status') -cne 'RESIDENT_UNINSTALLED_EVIDENCE_KEPT' -or $kept -cnotmatch '^C:\\ProgramData\\CluedIndependentCI\\resident-uninstalled-\d{8}T\d{6}Z-[0-9a-f]{12}$') {
    $report['after'] = [ordered]@{ residentRootExists = [IO.Directory]::Exists($ResidentRoot); services = @((Get-ScState 'CluedCIResident'), (Get-ScState 'CluedCISwapBroker')); processesUnderRoot = @(Get-ProcessesUnderRoot) }
    Stop-Launch 'UNINSTALL_NOT_COMPLETED' $report
  }
  $ledger = Join-Path $kept $LedgerEvidenceRelativeDirectory
  $report['evidence'] = [ordered]@{ keptAt = $kept
    installReceiptSha256 = (Get-FileSha (Join-Path $kept 'install\install-receipt.json')); haltSha256 = (Get-FileSha (Join-Path $kept 'state\HALT.json'))
    ledgerEntries = @(if ([IO.Directory]::Exists($ledger)) { [IO.Directory]::GetDirectories($ledger) | ForEach-Object { [IO.Path]::GetFileName($_) } })
    ledgerRelativeDirectory = $LedgerEvidenceRelativeDirectory; terminalEvidenceMatches = (Test-TerminalEvidence $kept)
    uninstallReceiptSha256 = (Get-FileSha (Join-Path $kept 'install\uninstall-receipt.json')) }
  if ($report['evidence'].uninstallReceiptSha256) { Write-New (Join-Path $Out 'uninstall-receipt.json') ([IO.File]::ReadAllBytes((Join-Path $kept 'install\uninstall-receipt.json'))) }
  $report['pausedKeptSha256'] = Get-FileSha (Join-Path $kept 'state\PAUSED.json')   # review m6
  $report['deletedAndRenamed'] = Wait-Until { (Get-ScState 'CluedCIResident').gone -and (Get-ScState 'CluedCISwapBroker').gone -and (Get-ScState 'CluedCIUpgrader').gone -and -not [IO.Directory]::Exists($ResidentRoot) } 120   # r7 r2: + the upgrader
  $report['services'] = @((Get-ScState 'CluedCIResident'), (Get-ScState 'CluedCISwapBroker'))
  Write-Json 'uninstall-report.json' $report
  $e = $report['evidence']
  if ($InstalledPausedSha256 -and $report['pausedKeptSha256'] -cne $InstalledPausedSha256) { Stop-Launch 'UNINSTALL_PAUSE_EVIDENCE_UNCONFIRMED' $report }   # review m6
  if (-not $report['deletedAndRenamed'] -or $e.installReceiptSha256 -cne $InstalledReceiptSha256 -or $e.haltSha256 -cne $InstalledHaltSha256 -or -not $e.uninstallReceiptSha256 -or -not $e.terminalEvidenceMatches -or @($e.ledgerEntries) -notcontains $HaltedBatchKey) { Stop-Launch 'UNINSTALL_EVIDENCE_OR_DELETION_UNCONFIRMED' $report }
  $Done.Add('uninstall')
  [ordered]@{ keptAt = $kept; planSha256 = $sha; uninstallReceiptSha256 = $e.uninstallReceiptSha256; haltSha256 = $e.haltSha256 }
}
# After a verified install the companion is started as its task defines it (the Owner, not elevated, conhost
# --headless); a failure here is recorded, it does not undo the install.
function Step-StartCompanion {
  Import-Module 'C:\Windows\System32\WindowsPowerShell\v1.0\Modules\ScheduledTasks\ScheduledTasks.psd1'
  $r = [ordered]@{ started = $false; error = $null; state = $null }
  try { Start-CompanionTask; $r.started = $true } catch { $r.error = $_.Exception.Message }
  $null = Wait-Until { @(Get-ProcessesUnderRoot | Where-Object { $_.name -eq 'node.exe' -and $_.commandLine -like '*companion-main.mjs*' }).Count -gt 0 } 30
  $r.state = [string](Get-ScheduledTask -TaskPath '\Clued\' -TaskName 'CluedCIResidentCompanion' -ErrorAction SilentlyContinue).State
  $r['companionProcesses'] = @(Get-ProcessesUnderRoot | Where-Object { $_.commandLine -like '*companion-main.mjs*' } | ForEach-Object { [ordered]@{ pid = $_.pid; name = $_.name } })
  $Done.Add('companion')
  $r
}
# b9bba67e reinstall (Owner Decisions dd7378d2 + c27b47ee): the reinstalled resident comes back with the HALT of the
# halted batch kept as evidence (state\ is carried over). In the same elevated session, ask the NEWLY installed,
# package-pinned rearm-resident.ps1 to re-arm for exactly that HALT. The script only writes the request; the service
# then proves quiescence on both hosts (the companion was just started), archives the remaining scene (the Linux
# half; the Windows half was archived above) and clears the HALT itself. Waits up to 6 minutes for the HALT to go.
# A refusal or a timeout is recorded; it does not undo the install (the Owner can re-arm separately).
function Step-Rearm {
  $r = [ordered]@{ requested = $false; cleared = $false; exit = $null; stdout = $null; stderr = $null; error = $null; haltAfter = $null; notNeeded = $false }
  # Quota phase 1 reinstall: the installed resident is PAUSED, not halted, and the new install starts with a fresh
  # state (its executed heads are backfilled from the carried ledgers). No HALT was pinned: there is nothing to re-arm.
  if ($null -eq $InstalledHaltSha256 -or -not [IO.File]::Exists((Join-Path $ResidentRoot 'state\HALT.json'))) { $r.notNeeded = $true; Write-Json 'rearm-report.json' $r; $Done.Add('rearm-not-needed'); return $r }
  try {
    $rearm = Join-Path $ResidentRoot ('resident\' + $ResidentManifestSha256 + '\windows\rearm-resident.ps1')
    if ((Get-FileSha $rearm) -cne $RearmSha256) { throw 'INSTALLED_REARM_SCRIPT_NOT_AS_PACKAGED' }
    $halt = Join-Path $ResidentRoot 'state\HALT.json'
    if ((Get-FileSha $halt) -cne $InstalledHaltSha256) { throw 'HALT_CHANGED_SINCE_REVIEW' }
    $c = Invoke-Child 'rearm' $rearm @('-Request', 'Rearm', '-ExpectedHaltSha256', $InstalledHaltSha256, '-Reason', $RearmReason)
    $r.exit = $c.exit; $r.stdout = (Tail $c.stdout); $r.stderr = (Tail $c.stderr)
    $r.requested = ($c.exit -eq 0 -and [string]$c.stdout -match 'REARM_REQUESTED_SERVICE_WILL_VERIFY')
    if ($r.requested) { $r.cleared = Wait-Until { -not [IO.File]::Exists($halt) } 360 }
    $r.haltAfter = Get-FileSha $halt
  } catch { $r.error = $_.Exception.Message }
  Write-Json 'rearm-report.json' $r
  $Done.Add('rearm')
  $r
}
# M5 (ADR 0022 section 4.4): the last step. The installed, package-pinned rearm-resident.ps1 -CompanionHeadless: preflight, pending
# marker, the credential box on the secure desktop (CluedCompanionTaskRegistrar.exe; the password goes from there to the Task Scheduler
# and nowhere else), the elevated side's qualification for up to 8 minutes, and the fall-back to the interactive token when it does not
# pass. A failure is recorded; the node then runs as before the switch (interactive token) and the Owner can run the step again.
function Step-CompanionHeadless {
  $r = [ordered]@{ ran = $false; exit = $null; status = $null; stdout = $null; error = $null }
  try {
    $rearm = Join-Path $ResidentRoot ('resident\' + $ResidentManifestSha256 + '\windows\rearm-resident.ps1')
    if ((Get-FileSha $rearm) -cne $RearmSha256) { throw 'INSTALLED_REARM_SCRIPT_NOT_AS_PACKAGED' }
    # M5-b (ADR 0023): with a companion account, the account switch (the distribution moves to the account; no password is typed).
    $accountArgs = $(if ($CompanionWslVhdxDirectory) { @('-CompanionAccount', '-WslVhdxDirectory', $CompanionWslVhdxDirectory) } else { @('-CompanionHeadless') })
    if ($CompanionMaintenance) {
      if (-not $CompanionWslVhdxDirectory -or -not $MaintenanceHostDropPin -or $MaintenanceHelperSha256 -cnotmatch '^[0-9a-f]{64}$') { throw 'ONE_UAC_MAINTENANCE_NOT_PINNED' }
      $helper = Join-Path $ResidentRoot ('resident\' + $ResidentManifestSha256 + '\windows\companion-maintenance.ps1')
      if ((Get-FileSha $helper) -cne $MaintenanceHelperSha256) { throw 'ONE_UAC_MAINTENANCE_HELPER_CHANGED' }
      . $helper
      $subject = @{ node=$NodeName; packageManifestSha256=$PackageManifestSha256; ciSourceManifestSha256=$CiSourceManifestSha256; residentManifestSha256=$ResidentManifestSha256; installReceiptSha256=(Get-CompanionMaintenanceHash (Read-CompanionMaintenanceBytes (Join-Path $ResidentRoot 'install\install-receipt.json') -Live)); rearmSha256=$RearmSha256; operatorSid=$OperatorSid; companionSid=$OwnerSid; runnerService=$RunnerService; runnerBinary=$RunnerBinary; runnerSddl=$RunnerSddl; wslDistribution=$MaintenanceWslDistribution; vhdxPath=(Get-CompanionMaintenanceRegisteredVhd $MaintenanceWslDistribution); targetVhdxPath=(Join-Path $CompanionWslVhdxDirectory 'ext4.vhdx') }
      # The existing child is already elevated. Maintenance never invokes
      # RunAs, Resume, the force-kill quiesce tail or a startup-type change.
      $maintenanceEvidence = Join-Path $StageParent ('maintenance-'+[guid]::NewGuid().ToString('N'))
      $r['maintenanceEvidenceDirectory'] = $maintenanceEvidence
      $c = Invoke-CompanionMaintenance -Root $ResidentRoot -ExpectedSubject $subject -HostDrop $MaintenanceHostDropPin -EvidenceDirectory $maintenanceEvidence -Action {
        param($contextFile,$contextSha)
        Invoke-Child 'companion-headless' $rearm ($accountArgs + @('-CompanionWslVmShutdown','-CompanionMaintenanceContextFile',$contextFile,'-ExpectedCompanionMaintenanceContextSha256',$contextSha))
      }
    } else { $c = Invoke-Child 'companion-headless' $rearm $accountArgs }
    $r.ran = $true; $r.exit = $c.exit; $r.stdout = (Tail $c.stdout)
    $r.status = if ([string]$c.stdout -match '"status":\s*"(COMPANION_HEADLESS_[A-Z_]+)"') { $Matches[1] } else { 'UNREADABLE' }
  } catch { $r.error = $_.Exception.Message; if ($CompanionMaintenance) { $r.status = 'COMPANION_MAINTENANCE_NOT_COMPLETED_PRESERVED' } }
  Write-Json 'companion-headless-report.json' $r
  $Done.Add('companion-headless')
  $r
}
