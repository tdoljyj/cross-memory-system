# r5 N7: the node identity keys, as the rule reads them: each name of $names (role = key name) looked up with $finder, which returns
# @{ key; origin } or $null. keys: role = origin ('tpm' | 'software') or $null; missing: the names not found; any missing is
# NODE_IDENTITY_KEY_MISSING; all there and the identity key not in the TPM is NODE_IDENTITY_KEY_NOT_TPM (M5 accepts a TPM identity key
# only: the host preparation's rule, Fable 11-21 "r5 node key" 3.3; the encryption key is in software, the TPM provider makes no
# key-agreement key). A key found is disposed of again.
function Test-NodeIdentityKeys($names, [scriptblock]$finder) {
  $keys = [ordered]@{}; $missing = New-Object Collections.Generic.List[string]
  foreach ($role in @($names.Keys)) {
    $found = & $finder $names[$role]
    if ($null -eq $found) { $keys[$role] = $null; $missing.Add([string]$names[$role]); continue }
    $keys[$role] = $found.origin
    if ($found.key -is [IDisposable]) { $found.key.Dispose() }
  }
  $notTpm = $null -ne $keys['identity'] -and [string]$keys['identity'] -cne 'tpm'
  [ordered]@{ keys = $keys; missing = @($missing); code = $(if ($missing.Count) { 'NODE_IDENTITY_KEY_MISSING' } elseif ($notTpm) { 'NODE_IDENTITY_KEY_NOT_TPM' } else { $null }) }
}
# r5 N7: read with the pinned registration script's own key names ($KeyNames, $TpmProviderName) and finder (Get-Providers,
# Find-MachineKey), taken from its pinned bytes by AST; its Fail (which exits) is replaced by a throw first. Nothing else of it runs.
function Get-NodeIdentityKeyCheck {
  $bytes = try { [IO.File]::ReadAllBytes([string]$FirstInstallRegistrationScript) } catch { $null }
  if ($null -eq $bytes -or (Sha256Bytes $bytes) -cne $FirstInstallRegistrationScriptSha256) { return [ordered]@{ keys = $null; missing = $null; code = 'NODE_REGISTRATION_SCRIPT_CHANGED' } }
  try {
    $tokens = $null; $errors = $null
    $ast = [Management.Automation.Language.Parser]::ParseInput($Strict8.GetString($bytes).TrimStart([char]0xFEFF), [ref]$tokens, [ref]$errors)
    if ($errors.Count) { throw 'REGISTRATION_SCRIPT_PARSE_ERRORS' }
    $parts = @()
    foreach ($n in @('Get-Providers', 'Find-MachineKey')) {
      $f = @($ast.FindAll({ param($x) $x -is [Management.Automation.Language.FunctionDefinitionAst] -and $x.Name -ceq $n }, $false))
      if ($f.Count -ne 1) { throw ('REGISTRATION_FUNCTION_NOT_ONE:' + $n) }
      $parts += $f[0].Extent.Text
    }
    foreach ($n in @('KeyNames', 'TpmProviderName')) {
      $a = @($ast.FindAll({ param($x) $x -is [Management.Automation.Language.AssignmentStatementAst] -and $x.Parent -is [Management.Automation.Language.NamedBlockAst] -and $x.Left.Extent.Text -ceq ('$' + $n) }, $false))
      if ($a.Count -ne 1) { throw ('REGISTRATION_ASSIGNMENT_NOT_ONE:' + $n) }
      $parts += $a[0].Extent.Text
    }
    Add-Type -AssemblyName System.Core
    function Fail([string]$Code, [string]$Detail) { throw ($Code + ': ' + $Detail) }
    foreach ($t in $parts) { . ([scriptblock]::Create($t)) }
    Test-NodeIdentityKeys $KeyNames { param($n) Find-MachineKey $n }
  } catch { [ordered]@{ keys = $null; missing = $null; code = 'NODE_IDENTITY_KEY_UNREADABLE'; error = [string]$_.Exception.Message } }
}
function Step-FirstInstallPreflight {
  if (Test-Path -LiteralPath 'function:Write-StepStart') { Write-StepStart }
  $residue = Get-FirstInstallResidue
  $report = [ordered]@{ root = $residue.root; services = $residue.services; directory = $FleetFirstInstallDirectory; directoryOk = $false; identityKeys = $null; codes = @() }
  if (Test-FirstInstallResiduePresent $residue) { $report.codes += 'FIRST_INSTALL_RESIDUE_PRESENT' }
  $report.identityKeys = Get-NodeIdentityKeyCheck   # r5 N7: the registration after install signs with them; a node without them is refused before anything changes
  if ($report.identityKeys.code) { $report.codes += [string]$report.identityKeys.code }
  try {
    $acl = [IO.Directory]::GetAccessControl($FleetFirstInstallDirectory)
    $sids = @($acl.GetAccessRules($true, $true, [Security.Principal.SecurityIdentifier]) | ForEach-Object { $_.IdentityReference.Value } | Sort-Object -Unique)
    $report.directoryOk = $acl.AreAccessRulesProtected -and ([IO.File]::GetAttributes($FleetFirstInstallDirectory) -band [IO.FileAttributes]::ReparsePoint) -eq 0 -and
      @($sids | Where-Object { $_ -cne 'S-1-5-18' -and $_ -cne 'S-1-5-32-544' }).Count -eq 0
  } catch { $report['error'] = $_.Exception.GetType().Name }
  if (-not $report.directoryOk) { $report.codes += 'FIRST_INSTALL_CREDENTIAL_DIRECTORY_NOT_ADMIN_ONLY' }
  Write-Json 'first-install-preflight-report.json' $report
  if (@($report.codes).Count) { Stop-Launch $report.codes[0] $report }
  $Done.Add('first-install-preflight')
}
# The first install's Windows side, read-only and complete, before Linux A (review H1): the runner as reviewed (waited for, as the
# reinstall's preflights wait), the two secret files where verify will look for them, and the install preflight itself (Step-Preflight:
# the installer's dry runs with and without the carried tokens, the ACL migration plan, the spool). Its result is kept; the install
# preflight after Linux (main region) returns it instead of running a second time into the same report names.
function Step-FirstInstallWindowsPreflight {
  if (Test-Path -LiteralPath 'function:Write-StepStart') { Write-StepStart }
  $report = [ordered]@{}; $codes = New-Object Collections.Generic.List[string]
  $runner = Wait-RunnerState; $report['runner'] = $runner
  if (-not $runner.ok) { $codes.Add('RUNNER_SERVICE_NOT_AS_REVIEWED') }
  $sec = Test-SecretsAsVerify; $report['secretsAsVerify'] = $sec; foreach ($q in @($sec.codes)) { $codes.Add($q) }
  $report['codes'] = @($codes)
  Write-Json 'first-install-windows-preflight-report.json' $report
  if ($codes.Count) { Stop-Launch $codes[0] $report }
  $script:FirstInstallPreflightResult = Step-Preflight
  $Done.Add('first-install-windows-preflight')
}
# Once the installer has placed the tokens, the host preparation's directory is deleted (its copies too: Remove-FleetCarry). Before the
# install it stays: the same command then runs again with it.
function Remove-FirstInstallCredentials {
  $d = [string]$FleetFirstInstallDirectory
  if (-not $d -or (Split-Path -Leaf $d) -cne 'credentials') { return }
  try {
    if ([IO.Directory]::Exists($d)) { if (([IO.File]::GetAttributes($d) -band [IO.FileAttributes]::ReparsePoint) -ne 0) { [IO.Directory]::Delete($d, $false) } else { [IO.Directory]::Delete($d, $true) } }
    $CarriedTokens['firstInstallCredentialsRemoved'] = -not [IO.Directory]::Exists($d)
  } catch { $CarriedTokens['firstInstallCredentialsRemoved'] = $false; $CarriedTokens['firstInstallCredentialsRemoveError'] = $_.Exception.GetType().Name }
}
# Linux A, then B (B-resume once after a failed B), then B's output by rule. A timeout stops the launch and kills nothing. Returns the
# staged copy of the version facts (and its hash) for verify -LinuxVersionFactsFile.
function Step-LinuxRoot {
  if (Test-Path -LiteralPath 'function:Write-StepStart') { Write-StepStart }
  $report = [ordered]@{ companionAccount = [bool]$FleetCompanionAccount; distribution = $FleetDistribution; planSha256 = $FleetPlanSha256; registrar = $null; runs = @(); evidence = $null; versionFacts = $null; codes = @() }
  # B's final status: a first install's B (reinstall/linux/first-install.py --in-dir) names itself; the rules for its output are the same
  $bDone = $(if ($FleetFirstInstall) { 'LINUX_FIRST_INSTALLED_RESIDENT_UPGRADE_TOOL_GENERATION_1' } else { 'LINUX_REINSTALLED_RESIDENT_UPGRADE_TOOL_GENERATION_1' })
  $stop = { param([string]$code) $report.codes = @($code); Write-Json 'linux-report.json' $report; Stop-Launch $code $report }
  # what a run leaves for its step line (task 87d330d0, 1.4): its seconds and the first {"dockerReady":...} line it printed, as printed
  # (never parsed: a passing run's own readings of the cold boot), or null. An aid: it never stops the launch.
  $stepDetail = { param($run) $ready = @(([string]$run.stdout) -split "`n" | ForEach-Object { $_.TrimEnd("`r") } | Where-Object { $_.StartsWith('{"dockerReady":') })
    [ordered]@{ seconds = $run.seconds; dockerReady = $(if ($ready.Count) { $ready[0] } else { $null }) } }
  if (Get-Variable -Name 'ResumeOriginalLauncherSha256' -ErrorAction SilentlyContinue) { & $stop 'FLEET_LAUNCH_RESUME_NOT_SUPPORTED' }
  Set-FleetLinuxDirectories
  $build = $null
  try {
    if ($FleetCompanionAccount) { try { $build = New-FleetRegistrar } catch { $report.registrar = [string]$_.Exception.Message; & $stop 'LINUX_REGISTRAR_BUILD_FAILED' }; $report.registrar = [ordered]@{ sha256 = $build.sha256 } }
    $exe = $(if ($build) { $build.exe } else { $null })
    if ($FleetCompanionAccount) { $report['outAclProbe'] = Step-LinuxOutAclProbe $exe }   # stops here, with nothing changed, when the account cannot write as planned
    $W1Restore.armed = $false   # from here phase A may have written: a stop is continued, the pause stays
    $a = Invoke-FleetLinuxScript 'A' $exe; $report.runs += ,(Get-FleetRunReport $a)
    # Lifted again only after a refusal that came before any change (Test-FleetRefusedBeforeAnyChange); any other refusal keeps the pause.
    if ($a.outcome -ceq 'REFUSED') { if (Test-FleetRefusedBeforeAnyChange $a.code) { $W1Restore.armed = $true } else { Set-FleetW1PauseKept ('PHASE_A_' + $a.code) } }
    if ($a.captureRefused) { & $stop 'LINUX_PHASE_A_OUTPUT_NOT_CAPTURED' }   # A ran and exited; what it printed is not readable yet (a continuation captures it)
    if ($a.outcome -ceq 'TIMEOUT') { & $stop 'LINUX_ROOT_RUN_TIMEOUT_NOTHING_KILLED' }
    if (-not (Test-FleetRun $a 'PHASE_A_DONE_NOTHING_SIGNED_NOTHING_INSTALLED')) { & $stop 'LINUX_PHASE_A_NOT_COMPLETED' }
    try { $Progress['detail'] = & $stepDetail $a } catch { }
    $Done.Add('linux-A')
    # r5 X1: a first install's B ends in the installer, which refuses a resident root that is there; whatever made one (or a service)
    # since the preflight, B does not start over it
    if ($FleetFirstInstall) {
      $residue = Get-FirstInstallResidue; $report['beforeLinuxB'] = $residue
      if (Test-FirstInstallResiduePresent $residue) { & $stop 'FIRST_INSTALL_ROOT_PRESENT_BEFORE_LINUX_B' }
    }
    if (-not $FleetFirstInstall) { [void](Read-VerifiedResidentLocks 'before-linux-b') }
    if (Get-Variable FleetCiConnectionB64 -ValueOnly -ErrorAction SilentlyContinue) {
      Confirm-FleetCiBeforeLinuxB
      $report['ciConnectionProofSha256'] = Get-FileSha (Get-FleetCiProofPath)
    }
    $b = Invoke-FleetLinuxScript 'B' $exe; $report.runs += ,(Get-FleetRunReport $b)
    if ($b.outcome -ceq 'TIMEOUT') { & $stop 'LINUX_ROOT_RUN_TIMEOUT_NOTHING_KILLED' }
    # B ran and exited, and its output could not be captured: whether it completed is not known here. Not "B did not complete" (no
    # resume is run over it): stopped like a timeout, and the continuation captures and checks the output (capture-file).
    if ($b.captureRefused) { & $stop 'LINUX_PHASE_B_OUTPUT_NOT_CAPTURED' }
    if (-not (Test-FleetRun $b $bDone)) {
      # The resume only after a B that ran and exited non-zero. A refusal or an unreadable result (B may never have started, or its
      # state is unknown) and an exit 0 without the final status are not a failed B: nothing more is run. B and B-resume both failing
      # stops here as well, with the node still paused and its Windows side untouched: an alarm for a person, on purpose.
      if (-not ($b.outcome -ceq 'EXITED' -and $b.exit -ne 0)) { & $stop 'LINUX_PHASE_B_NOT_COMPLETED' }
      if (-not $FleetFirstInstall) { [void](Read-VerifiedResidentLocks 'before-linux-b-resume') }
      if (Get-Variable FleetCiConnectionB64 -ValueOnly -ErrorAction SilentlyContinue) { Confirm-FleetCiBeforeLinuxB }
      $b = Invoke-FleetLinuxScript 'BResume' $exe; $report.runs += ,(Get-FleetRunReport $b)
      if ($b.outcome -ceq 'TIMEOUT') { & $stop 'LINUX_ROOT_RUN_TIMEOUT_NOTHING_KILLED' }
      if ($b.captureRefused) { & $stop 'LINUX_PHASE_B_OUTPUT_NOT_CAPTURED' }
      if (-not (Test-FleetRun $b $bDone)) { & $stop 'LINUX_PHASE_B_NOT_COMPLETED' }
    }
    try { $Progress['detail'] = & $stepDetail $b } catch { }
    $Done.Add('linux-B')
    $last = Parse-LastLine $b.stdout
    $ef = Get-FleetOutFile ([string](Get-Key $last 'evidence')) '^linux-live-manifest\.[0-9]{8}T[0-9]{6}Z\.txt$'
    $ff = Get-FleetOutFile ([string](Get-Key $last 'versionFacts')) '^linux-version-facts\.[0-9]{8}T[0-9]{6}Z\.json$'
    $report.evidence = $ef; $report.versionFacts = $ff
    if (-not $ef -or -not $ff) { & $stop 'LINUX_OUTPUT_PATHS_NOT_IN_THE_OUT_DIRECTORY' }
    $eb = Read-FleetOutFile ([IO.Path]::GetFileName($ef)) $b $exe 1048576; $fb = Read-FleetOutFile ([IO.Path]::GetFileName($ff)) $b $exe 1048576
    if ($null -eq $eb -or $null -eq $fb) { & $stop 'LINUX_OUTPUT_UNREADABLE' }   # missing, a link, a second name, not a plain file, or too large: nothing of it was read
  } finally { Remove-FleetRegistrar $build }
  $codes = Test-FleetLinuxOutput ($Strict8.GetString($eb)) ($Strict8.GetString($fb))
  if ($codes.Count -eq 0 -and (Get-Variable FleetInstalledPackageB64 -ValueOnly -ErrorAction SilentlyContinue)) {
    $sample = [DateTimeOffset]::MinValue; $now = [DateTimeOffset]::UtcNow
    $seen = Get-Key (Parse-Json ($Strict8.GetString($fb))) 'observedAt'
    if (-not [DateTimeOffset]::TryParse([string]$seen, [Globalization.CultureInfo]::InvariantCulture, [Globalization.DateTimeStyles]::AssumeUniversal, [ref]$sample) -or
        ($now - $sample).TotalMinutes -gt 15 -or ($sample - $now).TotalMinutes -gt 5) { $codes += 'LINUX_VERSION_FACTS_NOT_FRESH' }
  }
  if ($codes.Count) { $report.codes = @($codes); Write-Json 'linux-report.json' $report; Stop-Launch $codes[0] $report }
  # exactly the bytes that passed the rules, kept in this run's admin-only staging for verify
  $staged = Join-Path $Stage 'linux-version-facts.phase-B.json'; Write-New $staged $fb
  Write-New (Join-Path $Out 'linux-live-manifest.txt') $eb; Write-New (Join-Path $Out 'linux-version-facts.json') $fb
  $report['evidenceSha256'] = Sha256Bytes $eb; $report['versionFactsSha256'] = Sha256Bytes $fb
  Write-Json 'linux-report.json' $report
  $Done.Add('linux-output-checked')
  [ordered]@{ factsSource = $staged; factsSha256 = (Sha256Bytes $fb); evidenceSha256 = (Sha256Bytes $eb); runs = $report.runs }
}
