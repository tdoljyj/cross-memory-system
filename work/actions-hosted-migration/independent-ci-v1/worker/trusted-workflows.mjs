const fail = code => { throw Object.assign(new Error(code), { code }); };
const paths = new Set(Object.values(TRUSTED_WORKFLOW_PATHS)), table = {};
for (const row of ROWS) {
  const [path, sha256, blob, source] = row;
  // A malformed table is a broken Source: refuse at load, never accept a partial set.
  if (row.length !== 4 || !paths.has(path) || !/^[a-f0-9]{64}$/.test(sha256) || !/^[a-f0-9]{40}$/.test(blob)
    || !/^(?:main|pr-b) [a-f0-9]{40}$/.test(source) || Object.hasOwn(table, sha256)) fail('TRUSTED_WORKFLOW_TABLE_INVALID');
  table[sha256] = Object.freeze({ path, sha256, blob, source });
}
for (const path of paths) if (!ROWS.some(row => row[0] === path)) fail('TRUSTED_WORKFLOW_TABLE_INVALID');

// Keyed by the sha256 of the bytes.
export const TRUSTED_WORKFLOWS = Object.freeze(table);

const sets = Object.freeze(Object.fromEntries([...paths].map(path =>
  [path, Object.freeze(ROWS.filter(row => row[0] === path).map(row => row[1]))])));
// The exact accepted sha256 set of one workflow path (frozen, table order).
export function trustedWorkflowSha256s(path) {
  if (!Object.hasOwn(sets, path)) fail('TRUSTED_WORKFLOW_PATH_UNKNOWN');
  return sets[path];
}
