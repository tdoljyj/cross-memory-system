// The ONE table of hosted workflow bytes that the local formal roles trust in an installed Source (PR-A x PR-B).
// Every role, role policy and signed-result check derives its accepted set from here, on the Source v2 path
// (gitleaks v4, trivy v4 + required-trivy-v3, placement v2, policy v3, bridge v4) and on the H5 one-shot
// fallback (gitleaks v3, trivy v3 + required-trivy-v2, placement v1, policy v2, bridge v3).
//
// Each row is one exact reviewed version of one workflow, never a pattern: the sha256 of its bytes (the key),
// its git blob (for review against the commit), and where it comes from. The installed Source manifest declares
// exactly one row per workflow and its trusted checkout must hold exactly those bytes.
//
// Re-pin to a newly frozen PR-B commit (one command; it rewrites the rows below and the test fixture):
//   node work/actions-hosted-migration/independent-ci-v1/test/fixtures/repin-trusted-workflows.mjs --repo . --main <main rev> --pr-b <PR-B commit>
// Keep the 'main' rows while main still carries those bytes. Pure data: no I/O, no import.
